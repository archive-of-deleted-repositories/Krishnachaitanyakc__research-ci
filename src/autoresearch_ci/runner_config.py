"""Generate GPU runner configurations for Modal and RunPod."""

from __future__ import annotations

from autoresearch_ci.config import CIConfig


class RunnerConfig:
    """Generate runner provisioning scripts."""

    def generate_modal_config(self, config: CIConfig) -> str:
        """Generate a Modal deployment script for GPU experiments."""
        timeout_seconds = int(config.time_budget_hours * 3600)
        if config.gpu_count > 1:
            gpu_spec = f'modal.gpu.{config.gpu_type}(count={config.gpu_count})'
        else:
            gpu_spec = f'"{config.gpu_type}"'

        return f'''"""Modal GPU runner for autoresearch experiments."""
import modal

app = modal.App("autoresearch-experiment")

image = (
    modal.Image.debian_slim(python_version="{config.python_version}")
    .pip_install("numpy", "pyyaml")
)

@app.function(
    image=image,
    gpu={gpu_spec},
    timeout={timeout_seconds},
)
def run_experiment():
    """Run the autoresearch experiment on Modal."""
    import subprocess
    import json

    # Prepare data
    subprocess.run(["{config.prepare_command.split()[0]}"] + "{config.prepare_command}".split()[1:], check=True)

    # Train model
    subprocess.run(["{config.train_command.split()[0]}"] + "{config.train_command}".split()[1:], check=True)

    # Read results
    with open("results.json") as f:
        results = json.load(f)

    return results

@app.local_entrypoint()
def main():
    result = run_experiment.remote()
    print(f"Experiment result: {{result}}")
'''

    def generate_runpod_config(self, config: CIConfig) -> str:
        """Generate a RunPod provisioning shell script."""
        timeout_seconds = int(config.time_budget_hours * 3600)

        gpu_env = ""
        if config.gpu_count > 1:
            gpu_env = f'\nexport GPU_COUNT={config.gpu_count}\nexport GPU_TYPE={config.gpu_type}'

        return f'''#!/bin/bash
# RunPod GPU runner for autoresearch experiments
# Generated by autoresearch-ci

set -euo pipefail
{gpu_env}
echo "=== Setting up environment ==="
apt-get update -qq && apt-get install -y -qq python{config.python_version} python3-pip > /dev/null

echo "=== Installing dependencies ==="
pip install numpy pyyaml > /dev/null

echo "=== Preparing data ==="
{config.prepare_command}

echo "=== Running training ==="
timeout {timeout_seconds} {config.train_command}

echo "=== Results ==="
cat results.json

echo "=== Done ==="
'''

    def generate_self_hosted_setup(self, config: CIConfig) -> str:
        """Generate a setup script for self-hosted GitHub Actions runners."""
        return f'''#!/bin/bash
# Self-hosted runner setup for autoresearch experiments
# Generated by autoresearch-ci

set -euo pipefail

# Check GPU availability
if command -v nvidia-smi &> /dev/null; then
    echo "GPU detected:"
    nvidia-smi --query-gpu=name,memory.total --format=csv,noheader
else
    echo "WARNING: No GPU detected"
fi

# Set up Python environment
python{config.python_version} -m venv .venv
source .venv/bin/activate

pip install --upgrade pip
pip install numpy pyyaml

# Install project dependencies
if [ -f requirements.txt ]; then
    pip install -r requirements.txt
fi

echo "Runner environment ready."
'''
